"""
Alembic environment.

BASELINE NOTE (read this before running anything here):
The database already exists, fully built by database/init/01_extensions.sql
through 06_seed.sql, before this backend or Alembic ever touched it. This
env.py is wired so that:

  1. target_metadata points at the SAME Base/models the app uses (so a
     genuinely new future change — e.g. a column the AI team asks for later —
     can be autogenerated correctly against the real current state), and
  2. the connection URL is read from app.config.get_settings(), the exact
     same DATABASE_URL the FastAPI app uses — never a second, hand-maintained
     URL in alembic.ini that could point somewhere else.

To adopt the existing database as Alembic's baseline WITHOUT trying to
recreate it, see README.md section "Alembic baseline" — in short:

    alembic revision --autogenerate -m "baseline"   # must come out EMPTY
    alembic stamp head                               # record it as applied, run nothing

If the autogenerate step is NOT empty, STOP — that means Alembic sees a
difference between the live database and the SQLAlchemy models, which is
exactly the "genuine compatibility/error issue" the task brief says to
explain rather than silently paper over. Do not edit the generated
migration to force it through; find out why the diff exists.
"""
from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool

from alembic import context

# Import the app's own Base/engine config and every model module so
# Base.metadata is fully populated — this must mirror app/models/__init__.py.
from app.config import get_settings
from app.db import Base
from app.models import *  # noqa: F401,F403  (registers every model on Base.metadata)

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

# Single source of truth for the connection string: the same settings object
# app/db.py uses, not a separately maintained alembic.ini value.
settings = get_settings()
config.set_main_option("sqlalchemy.url", settings.database_url)


def run_migrations_offline() -> None:
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
